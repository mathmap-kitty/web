def _parab_pts(cx, w, vy, arm, n=24):
    a = (arm - vy) / (w * w)
    return " ".join(f"{cx-w+2*w*i/n:.1f},{a*(cx-w+2*w*i/n-cx)**2+vy:.1f}" for i in range(n+1))

